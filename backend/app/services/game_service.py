        # 策略：选择成语，让它们在字与字之间重叠
        words_data = []
        used_idioms = set()
        
        # 尝试生成的最大次数
        max_attempts = chain_length * 10
        attempts = 0
        
        while len(words_data) < chain_length and attempts < max_attempts:
            attempts += 1
            
            # 如果已有词，找一个可以重叠的位置
            if words_data:
                found_match = False
                
